"""External physical-file validators. Each tool's unfiltered output is retained verbatim."""
import json,os,re,shutil,subprocess,tempfile
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile
from collections import Counter
from math import dist
root=Path(__file__).resolve().parents[2]
out=Path(os.getenv('QA_INTEROP_OUT',root/'test-evidence/interop')).resolve()
tool=root.parent/'interop-tools'
def command(var,binary,local):
    return os.environ.get(var) or shutil.which(binary) or str(tool/local)
def cli(args,log,timeout=150):
    with log.open('w') as f:
        run=subprocess.run(list(map(str,args)),stdout=f,stderr=subprocess.STDOUT,timeout=timeout)
    return run.returncode,log.read_text(errors='replace')
def diagnostics(log):
    rows=[]
    for line in log.splitlines():
        rest=re.sub(r'\b0\s+(?:errors?|warnings?)\b','',line,flags=re.I)
        if re.search(r'warning|error|invalid|incomplete|unknown entity',rest,re.I):rows.append(line.strip())
    return rows
def schema(path):
    text=path.read_text(errors='replace')
    head=text.split('DATA;',1)[0]; ap='AP242' if 'AP242' in head.upper() else 'AP214' if 'AUTOMOTIVE_DESIGN' in head.upper() else 'UNKNOWN'
    if ap=='UNKNOWN':return {'schema':ap,'error':'unsupported schema: '+head}
    suffix='ap242' if ap=='AP242' else 'ap214e3'
    checker=command('STEPCODE_'+ap,'p21read_sdai_'+suffix,'step-build/bin/p21read_sdai_'+suffix)
    mm=bool(re.search(r'\bSI_UNIT\s*\(\s*\.MILLI\.\s*,\s*\.METRE\.\s*\)',text,re.I))
    # These files are generated by OpenCascade/FreeCAD. Mask strings and comments before resolving external-instance references.
    content=re.sub(r"'(?:''|[^'])*'|/\*.*?\*/",' ',text,flags=re.S)
    instances=re.findall(r'#(\d+)\s*=',content)
    unresolved=sorted(set(re.findall(r'#(\d+)',content))-set(instances))
    with tempfile.TemporaryDirectory() as tmp:
        status,log=cli([checker,'-s',path,Path(tmp)/'rewrite.stp'],out/(path.name+'.schema.log'))
    diagnostic=diagnostics(log)
    return {'schema':ap,'strictExit':status,'mm':mm,'entities':len(instances),'unresolved':unresolved,'duplicateIds':len(instances)-len(set(instances)),'diagnostics':diagnostic[:20]}
def slicer(path):
    binary=command('PRUSASLICER','prusa-slicer','PrusaSlicer.app/Contents/MacOS/PrusaSlicer')
    status,lines=cli([binary,'--info',path],out/(path.name+'.prusa.log'))
    fields=dict(re.findall(r'^([a-z_]+) =\s*([^\n]+)',lines,re.M))
    data={'exit':status,'manifold':fields.get('manifold'), 'volume':float(fields['volume']) if 'volume' in fields else None,
            'bbox':[[float(fields[k+'_'+a]) for a in 'xyz'] for k in ['min','max']] if 'min_x' in fields else None,'parts':fields.get('number_of_parts')}
    # Use an isolated temporary output and the same nominal printer/layer settings on each mesh.
    with tempfile.TemporaryDirectory() as tmp:
        gcode=Path(tmp)/'proof.gcode'
        sliced,log=cli([binary,'--export-gcode','--layer-height','0.30','--fill-density','0%','--output',gcode,path],out/(path.name+'.slice.log'))
        lines=gcode.read_text(errors='replace').splitlines() if gcode.exists() else []
        data['sliceExit']=sliced
        data['extrusionMoves']=sum(bool(re.search(r'^G1\b.* [XY]-?[0-9].* E[0-9]',line)) for line in lines)
    return data
def mf(path):
    ns={'m':'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'}
    with ZipFile(path) as z:
        doc=ET.fromstring(z.read('3D/3dmodel.model'))
        meshes=doc.findall('m:resources/m:object/m:mesh',ns)
        result=[]
        for m in meshes:
            v=[tuple(float(p.get(a)) for a in 'xyz') for p in m.find('m:vertices',ns)]
            tris=[tuple(int(f.get(k)) for k in ['v1','v2','v3']) for f in m.find('m:triangles',ns)]
            incidence=Counter();vol=0
            for t in tris:
                a,b,c=[v[i] for i in t];vol+=sum(a[i]*(b[(i+1)%3]*c[(i+2)%3]-b[(i+2)%3]*c[(i+1)%3]) for i in range(3))/6.
                for i,j in zip(t,(t[1],t[2],t[0])):incidence[tuple(sorted((v[i],v[j])))]+=1
            result.append({'bbox':[[min(row[k] for row in v) for k in range(3)],[max(row[k] for row in v) for k in range(3)]],'volume':vol,'closed':all(x==2 for x in incidence.values()),'triangles':len(tris)})
        data={'unit':doc.get('unit'),'meshes':result,'buildItems':len(doc.findall('m:build/m:item',ns)),'names':[o.get('name') for o in doc.findall('m:resources/m:object',ns)]}
        binary=command('PRUSASLICER','prusa-slicer','PrusaSlicer.app/Contents/MacOS/PrusaSlicer')
        status,log=cli([binary,'--info',path],out/(path.name+'.prusa.log'))
        data['slicerExit']=status
        data['slicerParts']=[{'volume':float(v),'manifold':flag=='yes'} for flag,v in re.findall(r'manifold = (yes|no).*?\bvolume = (-?[0-9.]+)',log,re.S)]
        return data
def vectors(dxf,svg):
    import ezdxf
    drawing=ezdxf.readfile(dxf);audit=drawing.audit()
    ents=drawing.modelspace().query('LWPOLYLINE[layer=="Graduation_outlines"]')
    xml=ET.parse(svg); svgroot=xml.getroot()
    height=float(svgroot.get('height').removesuffix('mm'));width=float(svgroot.get('width').removesuffix('mm'))
    polys=svgroot.findall('.//{http://www.w3.org/2000/svg}polygon[@data-layer="Graduation_outlines"]')
    if len(polys)!=len(ents):raise ValueError('DXF/SVG mark counts differ')
    groups=[[],[]];maxDiff=0
    for e,p in zip(ents,polys):
        xy=list(e.get_points('xy'))
        points=[(float(x),height-float(y)) for x,y in [t.split(',') for t in p.get('points').split()]]
        if len(xy)!=len(points) or not e.closed:raise ValueError('Tick contour is open/mismatched')
        maxDiff=max([maxDiff]+[dist(a,b) for a,b in zip(xy,points)])
        x=sum(i[0] for i in xy)/len(xy);y=sum(i[1] for i in xy)/len(xy)
        extent=max(i[1] for i in xy)-min(i[1] for i in xy)
        groups[0 if y>height/2 else 1].append((x,extent))
    return {'units':drawing.units,'auditErrors':len(audit.errors),'auditFixes':len(audit.fixes),'svgMm':[width,height],'maxDeltaBetweenContours':maxDiff,'edges':groups}
